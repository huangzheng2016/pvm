const jxaStateScript = `ObjC.import("AppKit");
const pb = $.NSPasteboard.generalPasteboard;
const front = $.NSWorkspace.sharedWorkspace.frontmostApplication;
JSON.stringify({
  count: Number(pb.changeCount),
  types: pb.types ? ObjC.deepUnwrap(pb.types) : [],
  front: front ? front.localizedName.js : "",
  pid: front ? Number(front.processIdentifier) : 0
});`

type darwinClipState struct {
	Count int      `json:"count"`
	Types []string `json:"types"`
	Front string   `json:"front"`
	PID   int      `json:"pid"`
}

func runJXA(script string, args ...string) (string, error) {
	argv := append([]string{"-l", "JavaScript", "-e", script}, args...)
	out, err := exec.Command("/usr/bin/osascript", argv...).Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func darwinClipboardState() (darwinClipState, error) {
	var st darwinClipState
	out, err := runJXA(jxaStateScript)
	if err != nil {
		return st, err
	}
	err = json.Unmarshal([]byte(out), &st)
	return st, err
}

func hasType(types []string, want string) bool {
	for _, t := range types {
		if t == want {
			return true
		}
	}
	return false
}

// darwinReadClipboard honors password-manager markers (Concealed, Transient,
// AutoGenerated) by returning ok=false before reading any payload.
func darwinReadClipboard(types []string) (clipContent, bool) {
	for _, blocked := range []string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"} {
		if hasType(types, blocked) {
			return clipContent{}, false
		}
	}
	if hasType(types, "public.file-url") || hasType(types, "NSFilenamesPboardType") {
		out, err := runJXA(`ObjC.import("AppKit");
const pb = $.NSPasteboard.generalPasteboard;
let paths = ObjC.deepUnwrap(pb.propertyListForType("NSFilenamesPboardType") || []);
if (!paths.length) {
  const urls = pb.readObjectsForClassesOptions([$.NSURL], $({NSPasteboardURLReadingFileURLsOnlyKey: true}));
  paths = urls ? ObjC.deepUnwrap(urls).map(u => ObjC.unwrap(u.path)) : [];
}
JSON.stringify(paths);`)
		if err == nil {
			var paths []string
			if json.Unmarshal([]byte(out), &paths) == nil && len(paths) > 0 {
				return clipContent{kind: "files", paths: paths}, true
			}
		}
	}
	if hasType(types, "public.png") {
		out, err := runJXA(`ObjC.import("AppKit");
const d = $.NSPasteboard.generalPasteboard.dataForType("public.png");
d ? d.base64EncodedStringWithOptions(0).js : "";`)
		if err == nil && out != "" {
			if b, err := base64.StdEncoding.DecodeString(out); err == nil && len(b) <= 16<<20 {
				return clipContent{kind: "png", data: b}, true
			}
		}
	}
	if hasType(types, "public.utf8-plain-text") {
		out, err := runJXA(`ObjC.import("AppKit");
const s = $.NSPasteboard.generalPasteboard.stringForType("public.utf8-plain-text");
s ? s.js : "";`)
		if err == nil && out != "" && len(out) <= 1<<20 {
			return clipContent{kind: "text", data: []byte(out)}, true
		}
	}
	return clipContent{}, false
}

func darwinSetClipboardFiles(paths []string) (int, error) {
	abs := make([]string, 0, len(paths))
	for _, p := range paths {
		a, err := filepath.Abs(p)
		if err != nil {
			return 0, err
		}
		abs = append(abs, a)
	}
	payload, _ := json.Marshal(abs)
	out, err := runJXA(`ObjC.import("AppKit");
const paths = ` + string(payload) + `;
const pb = $.NSPasteboard.generalPasteboard;
pb.clearContents;
const urls = paths.map(p => $.NSURL.fileURLWithPath($(p)));
pb.writeObjects(urls);
Number(pb.changeCount);`)
	if err != nil {
		return 0, err
	}
	return strconv.Atoi(strings.TrimSpace(out))
}

func darwinFetchVMFiles(b clipBridge, have string) (string, error) {
	s, err := b.openFiles()
	if err != nil {
		return "", err
	}
	defer s.Close()
	r := bufio.NewReader(s)
	line, err := r.ReadString('\n')
	if err != nil {
		return "", fmt.Errorf("read file list: %w", err)
	}
	key := strings.TrimSpace(line)
	if key == "" || key == have {
		_, _ = s.Write([]byte("n"))
		return "", nil
	}
	if _, err := s.Write([]byte("y")); err != nil {
		return "", err
	}
	if err := os.MkdirAll(b.stage, 0o700); err != nil {
		return "", err
	}
	dir, err := os.MkdirTemp(b.stage, "")
	if err != nil {
		return "", err
	}
	tops, err := extractClipFiles(r, dir, os.Stderr)
	if err == nil && len(tops) == 0 {
		err = fmt.Errorf("no files arrived")
	}
	if err != nil {
		os.RemoveAll(dir)
		return "", err
	}
	if _, err := darwinSetClipboardFiles(tops); err != nil {
		os.RemoveAll(dir)
		return "", err
	}
	if old, err := os.ReadDir(b.stage); err == nil {
		for _, e := range old {
			if filepath.Join(b.stage, e.Name()) != dir {
				os.RemoveAll(filepath.Join(b.stage, e.Name()))
			}
		}
	}
	return key, nil
}

func runClipboardBridge(vm string, clientPID int, clientDir string, b clipBridge) error {
	suffix := " [" + vm + "]"
	_ = suffix
	var focused bool
	seenCount := -1
	var sent [32]byte
	fetched := ""
	for {
		if err := syscall.Kill(clientPID, 0); err != nil {
			return nil
		}
		st, err := darwinClipboardState()
		if err != nil {
			time.Sleep(time.Second)
			continue
		}
		appName := strings.TrimSuffix(filepath.Base(clientDir), ".app")
		nowFocused := st.PID == clientPID || strings.EqualFold(st.Front, appName) || strings.EqualFold(st.Front, "Xpra")
		fromVM := false
		if b.toGuest && nowFocused && (!focused || st.Count != seenCount) && !fromVM {
			if c, ok := darwinReadClipboard(st.Types); ok {
				if sum := c.sum(); sum != sent {
					if err := b.send(c); err != nil {
						fmt.Fprintf(os.Stderr, "clipboard to %s: %v\n", vm, err)
					} else {
						sent = sum
					}
				}
			}
		}
		if b.toHost && focused && !nowFocused {
			key, err := darwinFetchVMFiles(b, fetched)
			if err != nil {
				fmt.Fprintf(os.Stderr, "files from %s: %v\n", vm, err)
			} else if key != "" {
				fetched = key
			}
		}
		focused, seenCount = nowFocused, st.Count
		time.Sleep(200 * time.Millisecond)
	}
}
