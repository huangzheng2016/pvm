func stubCmds(t *testing.T, existing ...string) {
	t.Helper()
	old := cmdExists
	cmdExists = func(name string) bool {
		for _, e := range existing {
			if name == e {
				return true
			}
		}
		return false
	}
	t.Cleanup(func() { cmdExists = old })
}

func TestResolveNAT(t *testing.T) {
	cases := []struct {
		name    string
		choice  string
		cmds    []string
		want    string
		wantErr bool
	}{
		{"auto prefers nft", "auto", []string{"nft", "iptables"}, NATNftables, false},
		{"auto empty choice", "", []string{"nft"}, NATNftables, false},
		{"auto falls to iptables", "auto", []string{"iptables"}, NATIptables, false},
		{"auto falls to userspace", "auto", nil, NATUserspace, false},
		{"explicit nft ok", "nft", []string{"nft"}, NATNftables, false},
		{"explicit nft missing", "nft", nil, "", true},
		{"explicit iptables ok", "iptables", []string{"iptables"}, NATIptables, false},
		{"explicit iptables missing", "iptables", []string{"nft"}, "", true},
		{"explicit userspace always ok", "userspace", nil, NATUserspace, false},
		{"unknown", "gre", nil, "", true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			stubCmds(t, c.cmds...)
			b, err := resolveNAT(c.choice)
			if c.wantErr {
				if err == nil {
					t.Fatalf("want error, got %v", b.name())
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if b.name() != c.want {
				t.Fatalf("got %s, want %s", b.name(), c.want)
			}
		})
	}
}

func TestIptablesRulesRender(t *testing.T) {
	rules := iptablesRules([]string{"pvmexit0", "pvmexit1"}, []string{"10.99.0.0/24", "10.99.1.0/24"})
	if len(rules) != 6 {
		t.Fatalf("got %d rules, want 6", len(rules))
	}
	joined := ""
	for _, r := range rules {
		joined += r[0] + "/" + r[1] + " " + r[2] + "\n"
	}
	for _, want := range []string{
		"nat/POSTROUTING -s 10.99.0.0/24 -m comment --comment pvm-exit -j MASQUERADE",
		"nat/POSTROUTING -s 10.99.1.0/24 -m comment --comment pvm-exit -j MASQUERADE",
		"filter/FORWARD -i pvmexit0 -m comment --comment pvm-exit -j ACCEPT",
		"filter/FORWARD -o pvmexit1 -m conntrack --ctstate ESTABLISHED,RELATED -m comment --comment pvm-exit -j ACCEPT",
	} {
		if !strings.Contains(joined, want) {
			t.Fatalf("missing rule %q in:\n%s", want, joined)
		}
	}
}

func TestParseMarkedDeletes(t *testing.T) {
	save := `# Generated by iptables-save
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A POSTROUTING -s 10.99.0.0/24 -m comment --comment "pvm-exit" -j MASQUERADE
-A POSTROUTING -s 10.97.0.0/24 -m comment --comment "pvm-exit" -j MASQUERADE
-A POSTROUTING -s 10.99.1.0/24 -m comment --comment "other" -j MASQUERADE
COMMIT
*filter
:FORWARD ACCEPT [0:0]
-A FORWARD -i pvmexit0 -m comment --comment "pvm-exit" -j ACCEPT
-A FORWARD -i pvmsp0 -m comment --comment "pvm-exit" -j ACCEPT
COMMIT
`
	deletes := parseMarkedDeletes(save, "pvm-exit", []string{"pvmexit0", "pvmexit1"}, []string{"10.99.0.0/24", "10.99.1.0/24"})
	if len(deletes) != 2 {
		t.Fatalf("got %d deletes, want 2 (other instances' rules untouched): %v", len(deletes), deletes)
	}
	first := strings.Join(deletes[0], " ")
	if first != "-t nat -D POSTROUTING -s 10.99.0.0/24 -m comment --comment pvm-exit -j MASQUERADE" {
		t.Fatalf("unexpected delete: %q", first)
	}
	second := strings.Join(deletes[1], " ")
	if !strings.HasPrefix(second, "-t filter -D FORWARD -i pvmexit0") {
		t.Fatalf("unexpected delete: %q", second)
	}
}
